"""Shared validation and masking helpers.

Kept free of model imports so drivers can be unit-tested against plain values.
"""

import re

from odoo.exceptions import ValidationError

ENV_KEY_RE = re.compile(r"^[A-Z_][A-Z0-9_]*$")
CONTAINER_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{1,62}$")
SECRET_KEY_RE = re.compile(r"(KEY|TOKEN|SECRET|PASSWORD)")

VOLUME_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")


def validate_env(env, reserved=()):
    """Return a ``dict[str, str]`` or raise ``ValidationError``.

    ``env`` may be ``None``/``False`` (an empty Json field). Values must be
    single-line: env-file syntax cannot represent newlines or NUL bytes.
    """
    if not env:
        return {}
    if not isinstance(env, dict):
        raise ValidationError("Environment must be a JSON object.")
    cleaned = {}
    for key, value in env.items():
        if not isinstance(key, str) or not ENV_KEY_RE.match(key):
            raise ValidationError(
                "Invalid environment variable name: %r. Use [A-Z_][A-Z0-9_]*."
                % (key,)
            )
        if key in reserved:
            raise ValidationError(
                "Environment variable %s is generated by Agent Hub and cannot "
                "be overridden." % key
            )
        if value is None:
            value = ""
        elif not isinstance(value, str):
            value = str(value)
        if "\n" in value or "\r" in value or "\x00" in value:
            raise ValidationError(
                "Environment variable %s contains a newline or NUL byte." % key
            )
        cleaned[key] = value
    return cleaned


def validate_volumes(volumes):
    """Validate the ``{name: {"bind": path, "mode": "rw"}}`` shape."""
    if not volumes:
        return {}
    if not isinstance(volumes, dict):
        raise ValidationError("Volumes must be a JSON object.")
    cleaned = {}
    for name, config in volumes.items():
        if not isinstance(name, str) or not VOLUME_KEY_RE.match(name):
            raise ValidationError("Invalid volume name: %r." % (name,))
        if not isinstance(config, dict) or not config.get("bind"):
            raise ValidationError(
                "Volume %s must be an object with a 'bind' path." % name
            )
        mode = config.get("mode", "rw")
        if mode not in ("rw", "ro"):
            raise ValidationError("Volume %s mode must be 'rw' or 'ro'." % name)
        cleaned[name] = {"bind": config["bind"], "mode": mode}
    return cleaned


def mask_env(env):
    """Return a copy with values of secret-looking keys replaced."""
    return {
        key: ("***" if SECRET_KEY_RE.search(key) else value)
        for key, value in (env or {}).items()
    }


def mask_text(text, secrets):
    """Replace every non-empty known secret value in ``text`` with ``***``."""
    text = text or ""
    for secret in secrets:
        if secret:
            text = text.replace(secret, "***")
    return text
