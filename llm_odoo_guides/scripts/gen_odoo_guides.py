#!/usr/bin/env python3
"""Regenerate ``data/llm_tool_guide_data.xml`` from a local docs checkout.

Offline counterpart to the runtime ``llm.odoo.guide.sync`` web update: renders
the same ``rst_renderer`` module and writes the seed XML. Set ``ODOO_DOCS`` to
the ``content/applications`` directory of an ``odoo/documentation`` checkout.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import rst_renderer

DOCS = os.environ.get(
    "ODOO_DOCS", "/tmp/odoo-documentation-19.0/content/applications"
)
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
OUT_XML = os.path.join(OUT_DIR, "llm_tool_guide_data.xml")


def xml_escape(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace('"', "&quot;").replace("'", "&apos;"))


def cdata(s):
    safe = s.replace("]]>", "]]]]><![CDATA[>")
    return "<![CDATA[%s]]>" % safe


def render_xml(all_guides):
    lines = ['<?xml version="1.0" encoding="utf-8" ?>',
             "<odoo noupdate=\"0\">",
             "    <!-- Odoo user documentation, converted to llm.tool.guide records.",
             "         Generated by gen_odoo_guides.py; served to agents through",
             "         odoo_model_guide_retriever. -->"]
    for g in all_guides:
        xml_id = g["code"].replace("-", "_").replace(".", "_")
        lines.append('    <record id="guide_%s" model="llm.tool.guide">' % xml_id)
        lines.append('        <field name="code">%s</field>' % xml_escape(g["code"]))
        lines.append('        <field name="title">%s</field>' % xml_escape(g["title"]))
        lines.append('        <field name="keyword">%s</field>' % xml_escape(g["keyword"]))
        if g["summary"]:
            lines.append('        <field name="summary">%s</field>' % xml_escape(g["summary"]))
        lines.append('        <field name="body">%s</field>' % cdata(g["body"]))
        lines.append("    </record>")
    lines.append("</odoo>")
    return "\n".join(lines) + "\n"


def main():
    all_guides = rst_renderer.build_all_guides(DOCS)
    codes = [g["code"] for g in all_guides]
    dupes = {c for c in codes if codes.count(c) > 1}
    if dupes:
        print("DUPLICATE CODES:", dupes)
        return 1
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(OUT_XML, "w", encoding="utf-8") as f:
        f.write(render_xml(all_guides))
    total_chars = sum(len(g["body"]) for g in all_guides)
    print("TOTAL GUIDES:", len(all_guides), "| total body chars:", total_chars)
    print("WROTE:", OUT_XML)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
